// ── Modprobe templates ───────────────────────────────────────────────────────

// Discrete mode template: enables DRM modeset
static MODPROBE_DISCRETE: &[u8] = br"# Automatically generated by system76-power
options nvidia-drm modeset=1
";

// Hybrid keeps the dGPU off while idle: runtime D3 (fine-grained) power
// management lets the NVIDIA driver power the GPU down between PRIME renders.
static MODPROBE_HYBRID: &[u8] = br"# Automatically generated by system76-power
options nvidia-drm modeset=1
options nvidia NVreg_DynamicPowerManagement=0x02
";

static MODPROBE_COMPUTE: &[u8] = br"# Automatically generated by system76-power
blacklist nvidia-drm
blacklist nvidia-modeset
alias nvidia-drm off
alias nvidia-modeset off
options nvidia NVreg_DynamicPowerManagement=0x02
";

static MODPROBE_INTEGRATED: &[u8] = br"# Automatically generated by system76-power
blacklist nouveau
blacklist nvidia
blacklist nvidia-drm
blacklist nvidia_uvm
blacklist nvidia-modeset
alias nouveau off
alias nvidia off
alias nvidia-drm off
alias nvidia-uvm off
alias nvidia-modeset off
";

// ── Suspend/sleep option templates ───────────────────────────────────────────

// Systems that cannot use other sleep options.
static SYSTEM_SLEEP_EMPTY: &[u8] = b"";

// Systems using S0ix must enable S0ix-based power management.
static SYSTEM_SLEEP_S0IX: &[u8] = br"# Preserve video memory through suspend
options nvidia NVreg_EnableS0ixPowerManagement=1
";

// Systems using S3 had suspend issues with WebRender.
static SYSTEM_SLEEP_S3: &[u8] = br"# Preserve video memory through suspend
options nvidia NVreg_PreserveVideoMemoryAllocations=1
";

// ── Xorg config template ─────────────────────────────────────────────────────

// The use of hybrid or discrete is determined by the "PrimaryGPU" option.
static XORG_CONF_DISCRETE: &[u8] = br#"# Automatically generated by system76-power
Section "OutputClass"
    Identifier "NVIDIA"
    MatchDriver "nvidia-drm"
    Driver "nvidia"
    Option "PrimaryGPU" "Yes"
    ModulePath "/lib/x86_64-linux-gnu/nvidia/xorg"
EndSection
"#;

// ── Path helpers ─────────────────────────────────────────────────────────────

pub(crate) fn get_xorg_conf_path() -> &'static str {
    if path::Path::new("/etc/X11/xorg.conf.d").exists() {
        "/etc/X11/xorg.conf.d/11-nvidia-discrete.conf"
    } else {
        "/usr/share/X11/xorg.conf.d/11-nvidia-discrete.conf"
    }
}

/// Returns the initramfs rebuild command and its single argument.
///
/// Exposed as `pub(crate)` so the daemon can invoke it from a background task
/// after a runtime switch, without blocking the D-Bus call.
pub(crate) fn update_initramfs_cmd() -> (&'static str, &'static str) {
    if path::Path::new("/usr/bin/dracut").exists() {
        ("reinstall-kernels", "")
    } else {
        ("update-initramfs", "-u")
    }
}

// ── PRIME helper ─────────────────────────────────────────────────────────────

pub(crate) fn get_prime_discrete() -> Result<String, GraphicsDeviceError> {
    fs::read_to_string(PRIME_DISCRETE_PATH)
        .map_err(GraphicsDeviceError::PrimeModeRead)
        .map(|mode| mode.trim().to_owned())
}

pub(crate) fn set_prime_discrete(mode: &str) -> Result<(), GraphicsDeviceError> {
    fs::write(PRIME_DISCRETE_PATH, mode).map_err(GraphicsDeviceError::PrimeModeWrite)
}

// ── Config writer ─────────────────────────────────────────────────────────────

/// Write all configuration files for the given graphics mode.
///
/// This is the shared core used by both `set_vendor` (boot-time path) and
/// `switch_runtime` (no-reboot path). It does NOT rebuild the initramfs —
/// callers are responsible for that step.
pub(crate) fn write_vendor_config(vendor: GraphicsMode) -> Result<(), GraphicsDeviceError> {
    let mode = match vendor {
        GraphicsMode::Hybrid => "on-demand\n",
        GraphicsMode::Discrete => "on\n",
        _ => "off\n",
    };

    let bonw15_hack = {
        let dmi_vendor = fs::read_to_string("/sys/class/dmi/id/sys_vendor").unwrap_or_default();
        let dmi_model = fs::read_to_string("/sys/class/dmi/id/product_version").unwrap_or_default();
        matches!(
            (dmi_vendor.trim(), dmi_model.trim()),
            ("System76", "bonw15") | ("System76", "bonw15-b")
        )
    };

    // Configure X server
    if vendor == GraphicsMode::Discrete {
        let mut file = fs::OpenOptions::new()
            .create(true)
            .truncate(true)
            .write(true)
            .open(get_xorg_conf_path())
            .map_err(GraphicsDeviceError::XserverConf)?;
        file.write_all(XORG_CONF_DISCRETE)
            .and_then(|()| file.sync_all())
            .map_err(GraphicsDeviceError::XserverConf)?;
    } else if path::Path::new(get_xorg_conf_path()).exists() {
        fs::remove_file(get_xorg_conf_path()).map_err(GraphicsDeviceError::XserverConf)?;
    }

    // Write modprobe config
    {
        log::info!("Creating {}", MODPROBE_PATH);

        let mut file = fs::OpenOptions::new()
            .create(true)
            .truncate(true)
            .write(true)
            .open(MODPROBE_PATH)
            .map_err(GraphicsDeviceError::ModprobeFileOpen)?;

        let text = match vendor {
            GraphicsMode::Integrated => MODPROBE_INTEGRATED,
            GraphicsMode::Hybrid => MODPROBE_HYBRID,
            GraphicsMode::Compute => MODPROBE_COMPUTE,
            GraphicsMode::Discrete => MODPROBE_DISCRETE,
        };

        file.write_all(text)
            .and_then(|()| file.sync_all())
            .map_err(GraphicsDeviceError::ModprobeFileWrite)?;

        // Power management must be configured depending on whether the system
        // uses S0ix or S3 for suspend.
        if vendor != GraphicsMode::Integrated {
            // XXX: Better way to check?
            let s0ix =
                fs::read_to_string("/sys/power/mem_sleep").unwrap_or_default().contains("[s2idle]");

            let (sleep, action) = if bonw15_hack {
                (SYSTEM_SLEEP_EMPTY, "disable")
            } else if s0ix {
                (SYSTEM_SLEEP_S0IX, "enable")
            } else {
                (SYSTEM_SLEEP_S3, "enable")
            };

            // We should also check if the GPU supports Video Memory Self
            // Refresh, but that requires already being in hybrid or nvidia
            // graphics mode. In compute mode, it just reports '?'.

            file.write_all(sleep)
                .and_then(|()| file.sync_all())
                .map_err(GraphicsDeviceError::ModprobeFileWrite)?;

            for service in
                &["nvidia-hibernate.service", "nvidia-resume.service", "nvidia-suspend.service"]
            {
                let status = process::Command::new(systemd::SYSTEMCTL_CMD)
                    .arg(action)
                    .arg(service)
                    .status()
                    .map_err(|why| GraphicsDeviceError::Command {
                        cmd: systemd::SYSTEMCTL_CMD,
                        why,
                    })?;

                if !status.success() {
                    // Error is ignored in case this service is removed
                    log::warn!(
                        "systemctl {} {}: failed with {} (not an error if service does not \
                         exist!)",
                        action,
                        service,
                        status
                    );
                }
            }
        }
    }

    log::info!("Setting {} to {}", PRIME_DISCRETE_PATH, mode);
    set_prime_discrete(mode)?;

    // Enable or disable nvidia-powerd based on the graphics mode.
    let action = match vendor {
        GraphicsMode::Compute | GraphicsMode::Hybrid | GraphicsMode::Discrete => {
            log::info!("Enabling NVIDIA services");
            "enable"
        }
        GraphicsMode::Integrated => {
            log::info!("Disabling NVIDIA services");
            "disable"
        }
    };

    for service in &["nvidia-powerd.service"] {
        // Arguments are `[action, service]`: systemctl's verb must come first,
        // otherwise it exits with "Unknown command verb 'nvidia-powerd.service'".
        let status = systemd::systemctl(&[action, service])
            .map_err(|why| GraphicsDeviceError::Command { cmd: systemd::SYSTEMCTL_CMD, why })?;

        if status.success() {
            log::info!("{}d {}", action, service);
            continue;
        }
        // Error is ignored in case this service is removed
        log::warn!("systemctl: failed with {} (not an error if service does not exist!)", status);
    }

    Ok(())
}

// ── Config snapshot ───────────────────────────────────────────────────────────

/// systemd units whose enablement `write_vendor_config` may change.
const MANAGED_UNITS: &[&str] = &[
    "nvidia-hibernate.service",
    "nvidia-resume.service",
    "nvidia-suspend.service",
    "nvidia-powerd.service",
];

/// The on-disk graphics configuration as it was before a runtime switch.
///
/// A failed switch restores this exactly, rather than regenerating config for
/// the live mode. That keeps a boot-time mode that was selected but not yet
/// rebooted into, and keeps the config consistent with the initramfs on disk
/// (the failure path does not rebuild it).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub(crate) struct ConfigSnapshot {
    /// Each managed file and its contents; `None` if it did not exist.
    files: Vec<(path::PathBuf, Option<Vec<u8>>)>,
    /// Each managed unit and whether it was enabled. Units in any other state
    /// (static, masked, not installed) are left untouched on restore.
    units: Vec<(&'static str, bool)>,
}

impl ConfigSnapshot {
    pub(crate) fn capture() -> Result<Self, GraphicsDeviceError> {
        let paths = [get_xorg_conf_path(), MODPROBE_PATH, PRIME_DISCRETE_PATH];
        let files = capture_files(paths.iter().map(path::Path::new))
            .map_err(GraphicsDeviceError::ConfigSnapshot)?;

        let mut units = Vec::new();
        for &unit in MANAGED_UNITS {
            if let Some(enabled) =
                unit_enablement(unit).map_err(GraphicsDeviceError::ConfigSnapshot)?
            {
                units.push((unit, enabled));
            }
        }

        Ok(Self { files, units })
    }

    /// Put every file and unit back as captured. Attempts every item even if
    /// one fails, then reports all failures together.
    pub(crate) fn restore(&self) -> Result<(), GraphicsDeviceError> {
        let mut failures = restore_files(&self.files);

        for &(unit, enabled) in &self.units {
            let (action, result) = if enabled {
                ("enable", systemd::enable(unit))
            } else {
                ("disable", systemd::disable(unit))
            };
            match result {
                Ok(status) if status.success() => (),
                Ok(status) => failures.push(format!("systemctl {} {}: {}", action, unit, status)),
                Err(why) => failures.push(format!("systemctl {} {}: {}", action, unit, why)),
            }
        }

        if failures.is_empty() {
            Ok(())
        } else {
            Err(GraphicsDeviceError::ConfigRestore(io::Error::other(failures.join("; "))))
        }
    }
}

fn capture_files<'a>(
    paths: impl IntoIterator<Item = &'a path::Path>,
) -> io::Result<Vec<(path::PathBuf, Option<Vec<u8>>)>> {
    paths
        .into_iter()
        .map(|path| match fs::read(path) {
            Ok(contents) => Ok((path.to_path_buf(), Some(contents))),
            Err(why) if why.kind() == io::ErrorKind::NotFound => Ok((path.to_path_buf(), None)),
            Err(why) => Err(io::Error::new(why.kind(), format!("{}: {}", path.display(), why))),
        })
        .collect()
}

/// Restore captured files, returning a description of each failure.
fn restore_files(files: &[(path::PathBuf, Option<Vec<u8>>)]) -> Vec<String> {
    let mut failures = Vec::new();
    for (path, contents) in files {
        let result = match contents {
            Some(contents) => fs::OpenOptions::new()
                .create(true)
                .truncate(true)
                .write(true)
                .open(path)
                .and_then(|mut file| file.write_all(contents).and_then(|()| file.sync_all())),
            None => match fs::remove_file(path) {
                Err(why) if why.kind() == io::ErrorKind::NotFound => Ok(()),
                other => other,
            },
        };
        if let Err(why) = result {
            failures.push(format!("{}: {}", path.display(), why));
        }
    }
    failures
}

/// `Some(true)` if `unit` is enabled, `Some(false)` if disabled, `None` for any
/// other state (static, masked, not installed, ...).
fn unit_enablement(unit: &str) -> io::Result<Option<bool>> {
    // `is-enabled` exits non-zero for disabled units, so only stdout matters.
    let output =
        process::Command::new(systemd::SYSTEMCTL_CMD).args(["is-enabled", unit]).output()?;
    Ok(match String::from_utf8_lossy(&output.stdout).trim() {
        "enabled" => Some(true),
        "disabled" => Some(false),
        _ => None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn snapshot_files_restore_contents_and_absence() {
        let dir = std::env::temp_dir().join(format!("s76_test_cfg_snapshot_{}", process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();

        let existing = dir.join("system76-power.conf");
        let absent = dir.join("11-nvidia-discrete.conf");
        fs::write(&existing, b"blacklist nouveau\n").unwrap();

        let snapshot = capture_files([existing.as_path(), absent.as_path()]).unwrap();

        // Simulate a switch rewriting one file and creating the other.
        fs::write(&existing, b"options nvidia-drm modeset=1\n").unwrap();
        fs::write(&absent, b"Section \"OutputClass\"\n").unwrap();

        assert!(restore_files(&snapshot).is_empty());
        assert_eq!(fs::read(&existing).unwrap(), b"blacklist nouveau\n");
        assert!(!absent.exists(), "a file absent at snapshot time must be removed again");

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn restore_files_reports_failures_and_continues() {
        let dir = std::env::temp_dir().join(format!("s76_test_cfg_restore_{}", process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();

        let good = dir.join("good");
        let snapshot = vec![
            (dir.join("missing-dir/file"), Some(b"x".to_vec())),
            (good.clone(), Some(b"ok".to_vec())),
        ];

        let failures = restore_files(&snapshot);
        assert_eq!(failures.len(), 1);
        assert_eq!(fs::read(&good).unwrap(), b"ok");

        let _ = fs::remove_dir_all(&dir);
    }
}
